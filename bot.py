def owners() -> set[int]:
    return {int(x.strip()) for x in os.getenv("OWNER_IDS", "").split(",") if x.strip().isdigit()}


def clean_name(value: str) -> str:
    value = re.sub(r"[^a-zA-Z0-9._-]+", "-", value.strip())
    return value.strip(".-_")[:48] or "forge-project"


def hex_color(value: str) -> int:
    value = value.strip().lstrip("#")
    if not re.fullmatch(r"[0-9a-fA-F]{6}", value):
        raise ValueError("Color must be a 6-digit hex value such as #42E8F4.")
    return int(value, 16)


def save_state(data: dict[str, Any]) -> None:
    tmp = DATA_FILE.with_suffix(".tmp")
    tmp.write_text(json.dumps(data, indent=2), encoding="utf-8")
    tmp.replace(DATA_FILE)


def load_state() -> dict[str, Any]:
    if not DATA_FILE.exists():
        return {"guilds": {}, "usage": {}}
    try:
        return json.loads(DATA_FILE.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {"guilds": {}, "usage": {}}


STATE = load_state()
HISTORY: dict[int, list[dict[str, str]]] = {}
COOLDOWN: dict[tuple[int, str], float] = {}


def guild_state(guild_id: int) -> dict[str, Any]:
    key = str(guild_id)
    STATE.setdefault("guilds", {}).setdefault(key, {"ai_enabled": True, "model": os.getenv("OPENAI_MODEL", "gpt-5.6-luna")})
    return STATE["guilds"][key]


def usage(user_id: int) -> None:
    key = str(user_id)
    STATE.setdefault("usage", {}).setdefault(key, 0)
    STATE["usage"][key] += 1
    save_state(STATE)


def allowed(interaction: discord.Interaction, seconds: float = 5.0) -> bool:
    key = (interaction.user.id, interaction.command.name if interaction.command else "unknown")
    now = time.monotonic()
    if now - COOLDOWN.get(key, 0) < seconds:
        return False
    COOLDOWN[key] = now
    return True


