@bot.tree.command(name="ask", description="Ask the ESN Forge AI assistant.")
@app_commands.describe(prompt="Your coding or project question")
async def ask(interaction: discord.Interaction, prompt: str):
    if not allowed(interaction):
        await interaction.response.send_message("⏳ Slow down for a moment.", ephemeral=True); return
    if interaction.guild and not guild_state(interaction.guild.id).get("ai_enabled", True):
        await interaction.response.send_message("AI is disabled for this server.", ephemeral=True); return
    await interaction.response.defer()
    usage(interaction.user.id)
    answer = await ask_openai(prompt, interaction.guild_id)
    HISTORY.setdefault(interaction.user.id, []).append({"q": prompt, "a": answer})
    HISTORY[interaction.user.id] = HISTORY[interaction.user.id][-8:]
    await interaction.followup.send(answer[:1900])


