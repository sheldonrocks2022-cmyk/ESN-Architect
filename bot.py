def make_zip(files: dict[str, str], root: str) -> io.BytesIO:
    stream = io.BytesIO()
    with zipfile.ZipFile(stream, "w", zipfile.ZIP_DEFLATED) as archive:
        for path, content in files.items():
            archive.writestr(f"{root}/{path}", content)
    stream.seek(0)
    return stream


def ast_review(code: str) -> list[str]:
    import ast
    findings: list[str] = []
    try:
        tree = ast.parse(code)
    except SyntaxError as exc:
        return [f"Syntax error on line {exc.lineno}: {exc.msg}"]
    dangerous = {"eval", "exec", "compile", "__import__"}
    for node in ast.walk(tree):
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id in dangerous:
            findings.append(f"Line {node.lineno}: avoid {node.func.id}() on untrusted input.")
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) and node.func.attr == "run":
            findings.append(f"Line {node.lineno}: review subprocess/process execution carefully.")
        if isinstance(node, ast.Constant) and isinstance(node.value, str):
            if re.search(r"(?:token|api[_-]?key|password|secret)\\s*[=:]\\s*['\"]", node.value, re.I):
                findings.append(f"Line {node.lineno}: possible hard-coded secret; move it to environment variables.")
    if not findings:
        findings.append("No obvious Python AST/security issues found. Add tests and validate external inputs.")
    return findings[:12]


async def ask_openai(prompt: str, guild_id: int | None = None) -> str:
    key = os.getenv("OPENAI_API_KEY", "").strip()
    if not key:
        return "OpenAI is not configured yet. Add OPENAI_API_KEY to .env and restart Forge."
    try:
        from openai import AsyncOpenAI
        client = AsyncOpenAI(api_key=key)
        model = os.getenv("OPENAI_MODEL", "gpt-5.6-luna")
        if guild_id:
            model = guild_state(guild_id).get("model") or model
        response = await client.responses.create(
            model=model,
            instructions="You are ESN Forge, a senior software engineer. Give concrete, safe, production-minded answers. Never expose or request secrets. When asked to generate code, provide complete runnable code rather than TODO placeholders.",
            input=prompt,
        )
        return response.output_text[:7000]
    except Exception as exc:
        log.exception("OpenAI request failed")
        return f"AI request failed: {type(exc).__name__}. Check OPENAI_MODEL, API access, and your key."


