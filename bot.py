@bot.tree.command(name="base64", description="Encode or decode Base64 text.")
@app_commands.describe(action="encode or decode", text="Text")
async def base64_tool(interaction: discord.Interaction, action: str, text: str):
    try:
        if action.lower() == "encode": result = base64.b64encode(text.encode()).decode()
        elif action.lower() == "decode": result = base64.b64decode(text.encode(), validate=True).decode()
        else: raise ValueError("Action must be encode or decode.")
        await interaction.response.send_message(f"```\n{result[:1800]}\n```", ephemeral=True)
    except Exception as exc:
        await interaction.response.send_message(f"❌ {exc}", ephemeral=True)


