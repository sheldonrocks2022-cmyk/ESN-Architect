def static_review(source: str) -> list[tuple[str, str]]:
    findings: list[tuple[str, str]] = []
    checks = [
        (r"(?:DISCORD_TOKEN|OPENAI_API_KEY|API_KEY)\s*=\s*['\"][^'\"]+['\"]", "high", "Hard-coded credential detected. Move secrets to environment variables."),
        (r"\b(?:eval|exec)\s*\(", "high", "Dynamic code execution detected. Do not pass untrusted input to eval/exec."),
        (r"except\s*:", "medium", "Bare exception handler detected. Catch specific exceptions and log the failure."),
        (r"subprocess\.(?:run|Popen|call)\([^\n]*shell\s*=\s*True", "high", "Shell execution with shell=True needs strict input validation."),
        (r"verify\s*=\s*False", "high", "TLS certificate verification is disabled."),
        (r"password\s*=\s*['\"]", "high", "Possible hard-coded password detected."),
    ]
    for pattern, severity, message in checks:
        if re.search(pattern, source, re.IGNORECASE):
            findings.append((severity, message))
    if not source.strip():
        findings.append(("medium", "No source code was provided."))
        return findings
    try:
        tree = ast.parse(source)
        function_count = sum(isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) for n in ast.walk(tree))
        class_count = sum(isinstance(n, ast.ClassDef) for n in ast.walk(tree))
        if function_count > 25:
            findings.append(("low", f"Large module: {function_count} functions detected. Consider splitting responsibilities."))
        if class_count > 15:
            findings.append(("low", f"Large module: {class_count} classes detected. Consider separating domains."))
    except SyntaxError as exc:
        findings.append(("high", f"Python syntax error at line {exc.lineno}: {exc.msg}"))
    if not findings:
        findings.append(("good", "No obvious high-risk patterns were detected by the static review."))
    return findings


