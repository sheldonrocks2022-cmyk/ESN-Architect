def clip(text: str, limit: int = 1800) -> str:
    text = str(text)
    return text if len(text) <= limit else text[: max(0, limit - 3)] + "..."


def code_block(text: str, language: str = "text") -> str:
    return f"```{language}\n{clip(text, 1700)}\n```"


def safe_project_name(name: str) -> str:
    cleaned = re.sub(r"[^A-Za-z0-9._ -]", "", name).strip().replace(" ", "-")
    return cleaned[:48] or "forge-project"


def command_identifier(name: str) -> str:
    value = re.sub(r"[^a-zA-Z0-9_ -]", "", name).strip().lower().replace(" ", "_").replace("-", "_")
    return value or "forge_command"


def validate_hex(value: str) -> str | None:
    value = value.strip().lstrip("#")
    return value.upper() if re.fullmatch(r"[0-9A-Fa-f]{6}", value) else None


def parse_owner_ids() -> set[int]:
    return {int(x.strip()) for x in os.getenv("OWNER_IDS", "").split(",") if x.strip().isdigit()}


